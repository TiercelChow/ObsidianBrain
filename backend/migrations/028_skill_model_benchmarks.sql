CREATE TABLE IF NOT EXISTS skill_benchmark_cases (
    id                  TEXT PRIMARY KEY,
    suite_id            TEXT NOT NULL REFERENCES skill_evaluation_suites(id) ON DELETE CASCADE,
    ordinal             INTEGER NOT NULL,
    name                TEXT NOT NULL,
    scenario_type       TEXT NOT NULL,
    fixture_json        TEXT NOT NULL,
    expectations_json   TEXT NOT NULL DEFAULT '{}',
    weight              REAL NOT NULL DEFAULT 1 CHECK (weight > 0),
    UNIQUE (suite_id, ordinal)
);

CREATE TABLE IF NOT EXISTS skill_benchmark_runs (
    id                  TEXT PRIMARY KEY,
    skill_id            TEXT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    skill_version_id    TEXT NOT NULL REFERENCES skill_versions(id) ON DELETE CASCADE,
    baseline_version_id TEXT NOT NULL REFERENCES skill_versions(id) ON DELETE CASCADE,
    suite_id            TEXT NOT NULL REFERENCES skill_evaluation_suites(id) ON DELETE CASCADE,
    knowledge_base_id   TEXT NOT NULL REFERENCES knowledge_bases(id) ON DELETE CASCADE,
    runtime_profile_id  TEXT NOT NULL REFERENCES agent_runtime_profiles(id) ON DELETE RESTRICT,
    model               TEXT NOT NULL DEFAULT '',
    status              TEXT NOT NULL CHECK (status IN ('queued', 'running', 'completed', 'failed')),
    total_cases         INTEGER NOT NULL DEFAULT 0,
    completed_cases     INTEGER NOT NULL DEFAULT 0,
    candidate_score     REAL,
    baseline_score      REAL,
    score_delta         REAL,
    passed              INTEGER NOT NULL DEFAULT 0 CHECK (passed IN (0, 1)),
    metrics_json        TEXT NOT NULL DEFAULT '{}',
    error               TEXT,
    started_at          TEXT,
    completed_at        TEXT,
    created_at          TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS skill_benchmark_case_results (
    run_id              TEXT NOT NULL REFERENCES skill_benchmark_runs(id) ON DELETE CASCADE,
    case_id             TEXT NOT NULL REFERENCES skill_benchmark_cases(id) ON DELETE CASCADE,
    variant             TEXT NOT NULL CHECK (variant IN ('baseline', 'candidate')),
    agent_run_id        TEXT REFERENCES agent_runs(id) ON DELETE SET NULL,
    response_text       TEXT NOT NULL DEFAULT '',
    citations_json      TEXT NOT NULL DEFAULT '[]',
    metrics_json        TEXT NOT NULL DEFAULT '{}',
    score               REAL NOT NULL CHECK (score >= 0 AND score <= 1),
    passed              INTEGER NOT NULL CHECK (passed IN (0, 1)),
    error               TEXT,
    PRIMARY KEY (run_id, case_id, variant)
);

CREATE INDEX IF NOT EXISTS idx_skill_benchmark_runs_version
    ON skill_benchmark_runs(skill_version_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_skill_benchmark_results_run
    ON skill_benchmark_case_results(run_id, variant, case_id);

